# 3. Evolução da Classe base 'City' do repositório da FIAP para o cenário VRP
class City:
    def __init__(self, id_local, x, y, name, demanda_caixas, prioridade):
        self.id = id_local
        self.x = x
        self.y = y
        self.name = name
        self.demanda_caixas = demanda_caixas
        self.prioridade = prioridade

    def distance(self, city):
        xDis = abs(self.x - city.x)
        yDis = abs(self.y - city.y)
        return math.sqrt((xDis ** 2) + (yDis ** 2))

