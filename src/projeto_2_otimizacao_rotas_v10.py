# Evolução da Classe Fitness para avaliação com aplicação de Hard Constraints
class Fitness:
    def __init__(self, rotas_decodificadas):
        self.rotas = rotas_decodificadas
        self.custo_total = 0.0
        self.fitness = 0.0

    def calcular_custo(self):
        distancia_total = 0
        penalidades = 0

        for viagem in self.rotas:
            dist_viagem = 0
            dist_acumulada = 0
            cidade_anterior = lista_cidades[0] # Origem (Hospital Central)

            for ordem_visita, id_cidade in enumerate(viagem):
                cidade_atual = lista_cidades[id_cidade]
                dist = cidade_anterior.distance(cidade_atual)
                dist_viagem += dist
                dist_acumulada += dist

                # Penalização baseada no SLA (Prioridade de entrega - Modelo original)
                peso_prioridade = 2.0 if cidade_atual.prioridade == 'Alta' else 0.5
                penalidades += (dist_acumulada * peso_prioridade)

                # --- NOVO: MULTA SEVERA DE SLA (REQUISITO EDITAL) ---
                # Se a carga for de Prioridade Alta (crítica/cadeia de frio) e ficar
                # para o final da rota (depois da 2ª paragem), aplica multa pesada.
                if cidade_atual.prioridade == 'Alta' and ordem_visita > 1:
                    penalidades += 5000
                # ----------------------------------------------------

                cidade_anterior = cidade_atual

            # Retorno ao Hospital
            dist_viagem += cidade_anterior.distance(lista_cidades[0])
            distancia_total += dist_viagem

            # Penalidade severa por violação de autonomia
            if dist_viagem > AUTONOMIA_MAXIMA:
                penalidades += 10000 * (dist_viagem - AUTONOMIA_MAXIMA) # Corrigido o operador *

        self.custo_total = distancia_total + penalidades
        return self.custo_total

    def get_fitness(self):
        if self.fitness == 0:
            self.fitness = 1.0 / (self.calcular_custo() + 1e-6)
        return self.fitness

# Funções ponte para integração limpa com as gerações do Algoritmo Genético
def decodificar_rota_vrp(cromossomo):
    viagens, viagem_atual, carga_atual = [], [], 0
    for local_id in cromossomo:
        demanda = lista_cidades[local_id].demanda_caixas
        if carga_atual + demanda > CAPACIDADE_MAXIMA_VEICULO:
            viagens.append(viagem_atual)
            viagem_atual = [local_id]
            carga_atual = demanda
        else:
            viagem_atual.append(local_id)
            carga_atual += demanda
    if viagem_atual:
        viagens.append(viagem_atual)
    return viagens

def calcular_fitness_vrp(cromossomo):
    rotas = decodificar_rota_vrp(cromossomo)
    fit = Fitness(rotas)
    return fit.get_fitness()

