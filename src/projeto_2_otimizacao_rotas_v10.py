"""# 🧪 BLOCO 4: Quality Assurance (QA) e Blindagem de Testes (Pytest)

Na engenharia de software moderna (cultura CI/CD), nenhum modelo de IA vai para produção sem **Testes Unitários**.
Utilizamos o framework `pytest` para aplicar o conceito de *Test-Driven Validation*:

- Simulamos rotas que forçam a quebra de regras (excesso de carga e de distância).
- O teste valida de forma autônoma (Asserts) se a Função Fitness aplica as penalidades corretamente. Isso blinda as regras de negócio contra falhas humanas ou futuras alterações no código base.
"""

import time

def heuristica_vizinho_mais_proximo():
    inicio = time.time()
    visitados = set([0]) # 0 é o Hospital (Origem)
    rota_atual = []
    rotas_finais = []
    carga_atual = 0
    cidade_atual = 0

    # Construção da rota gulosa
    while len(visitados) < len(lista_cidades):
        distancia_min = float('inf')
        proxima_cidade = -1

        for i in range(1, len(lista_cidades)):
            if i not in visitados:
                dist = lista_cidades[cidade_atual].distance(lista_cidades[i])
                if dist < distancia_min:
                    distancia_min = dist
                    proxima_cidade = i

        demanda = lista_cidades[proxima_cidade].demanda_caixas
        if carga_atual + demanda > CAPACIDADE_MAXIMA_VEICULO:
            rotas_finais.append(rota_atual)
            rota_atual = [proxima_cidade]
            carga_atual = demanda
        else:
            rota_atual.append(proxima_cidade)
            carga_atual += demanda

        visitados.add(proxima_cidade)
        cidade_atual = proxima_cidade

    if rota_atual:
        rotas_finais.append(rota_atual)

    fim = time.time()

    # Avaliação do custo usando a nossa classe Fitness (com restrições)
    fit_nn = Fitness(rotas_finais)
    custo_total = fit_nn.calcular_custo()

    return rotas_finais, custo_total, (fim - inicio)

